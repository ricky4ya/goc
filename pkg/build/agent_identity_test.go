func TestGeneratedAgentRuntimeIdentityUsesDedicatedValuesAndFallbacks(t *testing.T) {
	var generated bytes.Buffer
	err := coverMainTmpl.Execute(&generated, struct {
		Covers                   []*PackageCover
		GlobalCoverVarImportPath string
		Package                  string
		Host                     string
		Mode                     string
		CommitID                 string
		Branch                   string
		ProjectID                string
		ProjectPath              string
		ProjectName              string
		Extra                    string
	}{
		GlobalCoverVarImportPath: "example.test/cover",
		Package:                  "cover",
		Host:                     "coverage.example.test",
		Mode:                     "atomic",
		CommitID:                 "0123456789abcdef0123456789abcdef01234567",
		ProjectID:                "632",
		ProjectPath:              "qa/coverage_go",
		ProjectName:              "coverage_go",
	})
	if err != nil {
		t.Fatalf("render agent template: %v", err)
	}

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "agent.go", generated.Bytes(), 0)
	if err != nil {
		t.Fatalf("parse generated agent: %v", err)
	}
	wantedFunctions := map[string]bool{
		"firstNonEmptyEnv":            true,
		"coverageRelease":             true,
		"coverageDeployEnv":           true,
		"coverageNamespace":           true,
		"coverageBinary":              true,
		"validCoverageRelease":        true,
		"validCoverageDeployEnv":      true,
		"loadCoverageRuntimeIdentity": true,
	}
	var declarations bytes.Buffer
	for _, declaration := range file.Decls {
		switch typed := declaration.(type) {
		case *ast.FuncDecl:
			if wantedFunctions[typed.Name.Name] {
				if err := format.Node(&declarations, fset, typed); err != nil {
					t.Fatalf("format generated function %s: %v", typed.Name.Name, err)
				}
				declarations.WriteString("\n")
			}
		case *ast.GenDecl:
			for _, spec := range typed.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok || typeSpec.Name.Name != "coverageRuntimeIdentity" {
					continue
				}
				if err := format.Node(&declarations, fset, typed); err != nil {
					t.Fatalf("format generated runtime identity type: %v", err)
				}
				declarations.WriteString("\n")
				break
			}
		}
	}
	for name := range wantedFunctions {
		if !bytes.Contains(declarations.Bytes(), []byte("func "+name+"(")) {
			t.Fatalf("generated agent does not expose %s", name)
		}
	}

	if !bytes.Contains(declarations.Bytes(), []byte("type coverageRuntimeIdentity struct")) {
		t.Fatal("generated agent does not expose coverageRuntimeIdentity")
	}

	testDir := t.TempDir()
	runtimeSource := `package probe

import (
	"fmt"
	"io/ioutil"
	"os"
	"path/filepath"
	"strings"
)

` + declarations.String() + "\n"
	runtimeTest := `package probe

import "testing"

func TestCoverageRuntimeIdentity(t *testing.T) {
	t.Setenv("GOC_RELEASE", "api-tester")
	t.Setenv("ECHO_APP_ID", "legacy-api-tester")
	t.Setenv("GOC_DEPLOY_ENV", "test-r")
	t.Setenv("GOC_NAMESPACE", "qa")
	t.Setenv("NAMESPACE", "legacy-qa")
	t.Setenv("ECHO_VERSION", "")
	t.Setenv("ECHO_VESION", "test-t")

	identity, err := loadCoverageRuntimeIdentity()
	if err != nil {
		t.Fatalf("loadCoverageRuntimeIdentity() error = %v", err)
	}
	if identity.Release != "api-tester" || identity.DeployEnv != "test-r" || identity.Namespace != "qa" {
		t.Fatalf("identity = %+v", identity)
	}
	if identity.Binary == "" {
		t.Fatal("binary is empty")
	}

	t.Setenv("GOC_DEPLOY_ENV", "")
	if got := coverageDeployEnv(); got != "test-t" {
		t.Fatalf("legacy deploy env fallback = %q, want test-t", got)
	}
}

func TestCoverageRuntimeIdentityRejectsMissingRelease(t *testing.T) {
	t.Setenv("GOC_RELEASE", "")
	t.Setenv("ECHO_APP_ID", "")
	t.Setenv("GOC_DEPLOY_ENV", "default")
	t.Setenv("GOC_NAMESPACE", "qa")

	if _, err := loadCoverageRuntimeIdentity(); err == nil {
		t.Fatal("loadCoverageRuntimeIdentity() error = nil, want missing release error")
	}
}

func TestCoverageRuntimeIdentityRejectsInvalidDeployEnv(t *testing.T) {
	t.Setenv("GOC_RELEASE", "api-tester")
	t.Setenv("GOC_DEPLOY_ENV", "test-z")
	t.Setenv("GOC_NAMESPACE", "qa")

	if _, err := loadCoverageRuntimeIdentity(); err == nil {
		t.Fatal("loadCoverageRuntimeIdentity() error = nil, want invalid deploy env error")
	}
}
`
	if err := os.WriteFile(filepath.Join(testDir, "go.mod"), []byte("module example.test/probe\n\ngo 1.20\n"), 0o644); err != nil {
		t.Fatalf("write test module: %v", err)
	}
	if err := os.WriteFile(filepath.Join(testDir, "agent_env.go"), []byte(runtimeSource), 0o644); err != nil {
		t.Fatalf("write generated deploy-env function: %v", err)
	}
	if err := os.WriteFile(filepath.Join(testDir, "agent_env_test.go"), []byte(runtimeTest), 0o644); err != nil {
		t.Fatalf("write generated deploy-env test: %v", err)
	}
	command := exec.Command("go", "test", "./...")
	command.Dir = testDir
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("generated runtime identity behavior: %v\n%s", err, output)
	}
}
