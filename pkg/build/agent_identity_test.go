func TestLoadAgentBuildIdentity(t *testing.T) {
	t.Setenv("GOC_PROJECT_ID", "632")
	t.Setenv("GOC_PROJECT_PATH", "qa/coverage_go")
	t.Setenv("GOC_PROJECT_NAME", "coverage_go")
	t.Setenv("GOC_COMMIT_SHA", "0123456789abcdef0123456789abcdef01234567")
	t.Setenv("GOC_COMMIT_REF", "master")

	identity, err := loadAgentBuildIdentity()
	if err != nil {
		t.Fatalf("load identity: %v", err)
	}
	if identity.ProjectPath != "qa/coverage_go" || identity.CommitRef != "master" {
		t.Fatalf("unexpected identity: %+v", identity)
	}
}

func TestLoadAgentBuildIdentityRejectsShortSHA(t *testing.T) {
	t.Setenv("GOC_PROJECT_ID", "632")
	t.Setenv("GOC_PROJECT_PATH", "qa/coverage_go")
	t.Setenv("GOC_PROJECT_NAME", "coverage_go")
	t.Setenv("GOC_COMMIT_SHA", "01234567")

	if _, err := loadAgentBuildIdentity(); err == nil {
		t.Fatal("expected short SHA to be rejected")
	}
}

func TestGeneratedAgentDeployEnvFallsBackToLegacySpelling(t *testing.T) {
	var generated bytes.Buffer
	err := coverMainTmpl.Execute(&generated, struct {
		Covers                   []*PackageCover
		GlobalCoverVarImportPath string
		Package                  string
		Host                     string
		Mode                     string
		CommitID                 string
		Branch                   string
		ProjectID                string
		ProjectPath              string
		ProjectName              string
		Extra                    string
	}{
		GlobalCoverVarImportPath: "example.test/cover",
		Package:                  "cover",
		Host:                     "coverage.example.test",
		Mode:                     "atomic",
		CommitID:                 "0123456789abcdef0123456789abcdef01234567",
		ProjectID:                "632",
		ProjectPath:              "qa/coverage_go",
		ProjectName:              "coverage_go",
	})
	if err != nil {
		t.Fatalf("render agent template: %v", err)
	}

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "agent.go", generated.Bytes(), 0)
	if err != nil {
		t.Fatalf("parse generated agent: %v", err)
	}
	var deployEnvFunc *ast.FuncDecl
	for _, declaration := range file.Decls {
		if function, ok := declaration.(*ast.FuncDecl); ok && function.Name.Name == "coverageDeployEnv" {
			deployEnvFunc = function
			break
		}
	}
	if deployEnvFunc == nil {
		t.Fatal("generated agent does not expose coverageDeployEnv")
	}

	var functionSource bytes.Buffer
	if err := format.Node(&functionSource, fset, deployEnvFunc); err != nil {
		t.Fatalf("format generated deploy-env function: %v", err)
	}

	testDir := t.TempDir()
	runtimeSource := "package probe\n\nimport \"os\"\n\n" + functionSource.String() + "\n"
	runtimeTest := `package probe

import "testing"

func TestCoverageDeployEnv(t *testing.T) {
	t.Setenv("ECHO_VERSION", "")
	t.Setenv("ECHO_VESION", "test-t")
	if got := coverageDeployEnv(); got != "test-t" {
		t.Fatalf("legacy fallback = %q, want test-t", got)
	}

	t.Setenv("ECHO_VERSION", "test-s")
	if got := coverageDeployEnv(); got != "test-s" {
		t.Fatalf("canonical value = %q, want test-s", got)
	}
}
`
	if err := os.WriteFile(filepath.Join(testDir, "go.mod"), []byte("module example.test/probe\n\ngo 1.20\n"), 0o644); err != nil {
		t.Fatalf("write test module: %v", err)
	}
	if err := os.WriteFile(filepath.Join(testDir, "agent_env.go"), []byte(runtimeSource), 0o644); err != nil {
		t.Fatalf("write generated deploy-env function: %v", err)
	}
	if err := os.WriteFile(filepath.Join(testDir, "agent_env_test.go"), []byte(runtimeTest), 0o644); err != nil {
		t.Fatalf("write generated deploy-env test: %v", err)
	}
	command := exec.Command("go", "test", "./...")
	command.Dir = testDir
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("generated deploy-env behavior: %v\n%s", err, output)
	}
}
