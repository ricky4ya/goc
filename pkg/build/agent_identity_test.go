func TestLoadAgentBuildIdentity(t *testing.T) {
	t.Setenv("GOC_PROJECT_ID", "632")
	t.Setenv("GOC_PROJECT_PATH", "qa/coverage_go")
	t.Setenv("GOC_PROJECT_NAME", "coverage_go")
	t.Setenv("GOC_COMMIT_SHA", "0123456789abcdef0123456789abcdef01234567")
	t.Setenv("GOC_COMMIT_REF", "master")

	identity, err := loadAgentBuildIdentity()
	if err != nil {
		t.Fatalf("load identity: %v", err)
	}
	if identity.ProjectPath != "qa/coverage_go" || identity.CommitRef != "master" {
		t.Fatalf("unexpected identity: %+v", identity)
	}
}

